"""Build the self-contained web pages (chat page, guide page, brand kit).

Edit the sources in site/src/ (index.html = chat page, guide.html, brand-kit.html, styles.css,
chat.css, main.js, chat.js, fonts/),
then run from the project root:

    .venv\\Scripts\\python.exe site\\build.py

It writes site/index.html, site/guide.html and site/brand-kit.html with the stylesheet, script, images and
font inlined, so each page renders correctly however it is opened: double-clicked from
disk, previewed in an editor, attached to an email, or served by any web server.
Links to other project files (../docs/..., sample-report.html) stay relative.

Host Grotesk is licensed under the SIL Open Font License 1.1, which allows embedding.
"""

from __future__ import annotations

import base64
import re
from pathlib import Path

SITE = Path(__file__).resolve().parent
SRC = SITE / "src"
MIME = {".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp", ".svg": "image/svg+xml", ".woff2": "font/woff2"}
BANNER = "<!-- Generated by site/build.py from site/src/. Edit the sources there, not this file. -->"


def data_uri(path: Path) -> str:
    mime = MIME.get(path.suffix.lower(), "application/octet-stream")
    return f"data:{mime};base64,{base64.b64encode(path.read_bytes()).decode('ascii')}"


def inline_css(css: str) -> str:
    # url(fonts/x.woff2) -> url(data:font/woff2;base64,...)
    return re.sub(r"url\((['\"]?)(fonts/[^)'\"]+)\1\)", lambda m: f"url({data_uri(SRC / m.group(2))})", css)


PAGES = ("index.html", "guide.html", "brand-kit.html")  # chat page, guide page, design-system sheet
STYLESHEET_RE = re.compile(r'<link rel="stylesheet" href="([\w.-]+\.css)">')
SCRIPT_RE = re.compile(r'<script src="([\w.-]+\.js)" defer></script>')


def build(name: str) -> Path:
    html = (SRC / name).read_text(encoding="utf-8")
    if not STYLESHEET_RE.search(html):
        raise SystemExit(f"{name}: no stylesheet link found")
    # Scripts at the end of <body> run after the DOM is parsed, so inlining keeps `defer` semantics.
    html = STYLESHEET_RE.sub(lambda m: f"<style>\n{inline_css((SRC / m.group(1)).read_text(encoding='utf-8'))}\n</style>", html)
    html = SCRIPT_RE.sub(lambda m: f"<script>\n{(SRC / m.group(1)).read_text(encoding='utf-8')}\n</script>", html)
    html = re.sub(r'src="(assets/img/[^"]+)"', lambda m: f'src="{data_uri(SITE / m.group(1))}"', html)
    html = html.replace("<!doctype html>", f"<!doctype html>\n{BANNER}", 1)

    leftovers = re.findall(r'(?:href|src)="(?:[\w.-]+\.(?:css|js)|assets/[^"]*)"', html)
    if leftovers:
        raise SystemExit(f"{name}: unresolved local assets {leftovers}")
    out = SITE / name
    out.write_text(html, encoding="utf-8")
    return out


if __name__ == "__main__":
    for page in PAGES:
        path = build(page)
        print(f"wrote {path.relative_to(SITE.parent)} ({path.stat().st_size / 1024:.0f} KB)")
